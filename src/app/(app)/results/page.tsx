import Link from "next/link";
import { requireUser } from "@/lib/auth";
import { getLatestAssessmentWithPrediction, getAssessmentHistory } from "@/lib/data";
import { PageTransition } from "@/components/animations/page-transition";
import { StaggerContainer, StaggerItem } from "@/components/animations/stagger";
import { Card, SectionHeader } from "@/components/ui/card";
import { ScoreRing } from "@/components/ui/score-ring";
import { ScoreBar } from "@/components/ui/score-bar";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/empty-state";
import { ContributionChart } from "@/components/charts/contribution-chart";
import { formatDate, toneClasses } from "@/lib/utils";
import { CATEGORY_LABELS, type Category, type Recommendation } from "@/lib/scoring";
import { FileSearch, Sparkles } from "lucide-react";

export const dynamic = "force-dynamic";

export default async function ResultsPage() {
  const user = await requireUser();
  const { assessment, prediction } = await getLatestAssessmentWithPrediction(user.id);
  const history = await getAssessmentHistory(user.id);

  if (!assessment || !prediction) {
    return (
      <PageTransition>
        <SectionHeader title="Your Placement Readiness" />
        <EmptyState
          icon={<Sparkles className="h-8 w-8" />}
          title="No assessment yet"
          description="Complete your first Placement Readiness Assessment to see a detailed, explainable report."
          action={
            <Link href="/assessment">
              <Button>Start Assessment</Button>
            </Link>
          }
        />
      </PageTransition>
    );
  }

  const previousScore = history.length > 1 ? history[history.length - 2]?.score : null;
  const delta = previousScore !== null && previousScore !== undefined ? prediction.score - previousScore : null;
  const tone = toneClasses(
    prediction.score >= 75 ? "success" : prediction.score >= 60 ? "primary" : prediction.score >= 40 ? "warning" : "danger",
  );
  const breakdown = prediction.breakdown as Record<Category, number>;
  const recommendations = prediction.recommendations as Recommendation[];

  return (
    <PageTransition>
      <div className="mb-6 flex flex-wrap items-center justify-between gap-3">
        <SectionHeader
          title="Your Placement Readiness"
          description={`Assessment completed successfully. Last updated: ${formatDate(assessment.createdAt)}`}
        />
        <Link href="/results/history">
          <Button variant="outline">
            <FileSearch className="h-4 w-4" /> View History
          </Button>
        </Link>
      </div>

      <StaggerContainer className="flex flex-col gap-6">
        <StaggerItem>
          <Card className="flex flex-col items-center gap-6 p-8 text-center sm:flex-row sm:text-left">
            <ScoreRing score={prediction.score} />
            <div>
              <p className={`text-lg font-semibold ${tone.text}`}>{prediction.level}</p>
              {delta !== null ? (
                <p className="mt-1 text-sm font-medium text-text-secondary">
                  {delta >= 0 ? "↑" : "↓"} {Math.abs(delta)} points since your previous assessment
                </p>
              ) : null}
              <p className="mx-auto mt-3 max-w-md text-sm text-text-secondary sm:mx-0">
                Your current readiness score is {prediction.score}/100. This is not a guarantee of placement — it&apos;s a
                transparent snapshot of where you stand today, generated by model version {prediction.modelVersion}.
              </p>
            </div>
          </Card>
        </StaggerItem>

        <StaggerItem>
          <Card>
            <SectionHeader title="Readiness Breakdown" />
            <div className="grid gap-5 sm:grid-cols-2">
              {(Object.keys(CATEGORY_LABELS) as Category[]).map((cat) => (
                <ScoreBar key={cat} label={CATEGORY_LABELS[cat]} value={breakdown[cat] ?? 0} />
              ))}
            </div>
          </Card>
        </StaggerItem>

        <StaggerItem>
          <div className="grid gap-6 lg:grid-cols-2">
            <Card>
              <SectionHeader title="Your Strengths" />
              <ul className="flex flex-col gap-2.5">
                {prediction.positiveFactors.map((f) => (
                  <li key={f} className="flex items-center gap-2 text-sm text-text">
                    <Badge tone="success">✓</Badge> {f}
                  </li>
                ))}
              </ul>
            </Card>
            <Card>
              <SectionHeader title="Focus Areas" />
              <ol className="flex flex-col gap-2.5">
                {prediction.improvementFactors.map((f, i) => (
                  <li key={f} className="flex items-center gap-2 text-sm text-text">
                    <span className="flex h-5 w-5 items-center justify-center rounded-full bg-primary-soft text-xs font-semibold text-primary">
                      {i + 1}
                    </span>
                    {f}
                  </li>
                ))}
              </ol>
            </Card>
          </div>
        </StaggerItem>

        <StaggerItem>
          <Card>
            <SectionHeader title="Why your score is what it is" description="Feature contribution to your final readiness score." />
            <ContributionChart data={prediction.featureContributions as { label: string; value: number }[]} />
          </Card>
        </StaggerItem>

        <StaggerItem>
          <Card>
            <SectionHeader title="Personalized Recommendations" description="Ranked actions with expected impact on your score." />
            <div className="flex flex-col gap-4">
              {recommendations.map((rec, idx) => (
                <div key={rec.title} className="flex gap-4 rounded-xl border border-border p-4">
                  <span className="text-2xl font-semibold text-primary/40">{String(idx + 1).padStart(2, "0")}</span>
                  <div className="flex-1">
                    <p className="font-semibold text-text">{rec.title}</p>
                    <div className="mt-1 flex items-center gap-3 text-xs text-text-secondary">
                      <span>
                        Current: <b className="text-text">{rec.current}</b>
                      </span>
                      <span>
                        Target: <b className="text-text">{rec.target}</b>
                      </span>
                    </div>
                    <p className="mt-2 text-sm text-text-secondary">{rec.action}</p>
                    <p className="mt-2 text-xs font-medium text-success">Expected impact: {rec.impact}</p>
                  </div>
                </div>
              ))}
            </div>
            <div className="mt-5 flex flex-wrap gap-3">
              <Link href="/roadmap">
                <Button variant="secondary">View Career Roadmap</Button>
              </Link>
              <Link href="/simulator">
                <Button variant="outline">Try What-If Simulator</Button>
              </Link>
            </div>
          </Card>
        </StaggerItem>
      </StaggerContainer>
    </PageTransition>
  );
}
